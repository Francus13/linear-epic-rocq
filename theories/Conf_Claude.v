(* ========================================================================== *)
(* PART 1.  Abstract rewriting: confluence modulo an equivalence              *)
(* ========================================================================== *)

(* This part is independent of LinOpal.  The setting is a reduction relation
   [step] on some type [A], an equivalence [eqv] (for us: structural and
   alpha equivalence), and an invariant [Inv] (for us: well-formedness).

   The main theorem [confluence_modulo] says that if
     (1) [eqv] is a simulation for [step]   (eqv ; step  ⊆  step ; eqv), and
     (2) [step] has the diamond property modulo [eqv] on [Inv] elements,
         where each side may also take zero steps,
   then [step] is confluent modulo [eqv]:
     t ->* t1  and  t ->* t2   implies   t1 ->* t3, t2 ->* t4, t3 ~ t4.

   This is the shape of the argument in Huet, "Confluent Reductions" (1980),
   specialised to the case where the local diamond closes in one step.  No
   termination assumption is needed. *)

Section AbstractConfluence.

  Variable A : Type.
  Variable step : A -> A -> Prop.
  Variable eqv : A -> A -> Prop.
  Variable Inv : A -> Prop.

  Hypothesis eqv_refl : forall x, eqv x x.
  Hypothesis eqv_sym : forall x y, eqv x y -> eqv y x.
  Hypothesis eqv_trans : forall x y z, eqv x y -> eqv y z -> eqv x z.

  Hypothesis Inv_step : forall x y, Inv x -> step x y -> Inv y.
  Hypothesis Inv_eqv : forall x y, Inv x -> eqv x y -> Inv y.

  (* (1) Equivalent terms can take matching steps. *)
  Hypothesis eqv_sim :
    forall x x' y, eqv x x' -> step x y ->
      exists y', step x' y' /\ eqv y y'.

  (* (2) The local diamond, modulo eqv, with optional steps. *)
  Hypothesis local_diamond :
    forall x y1 y2, Inv x -> step x y1 -> step x y2 ->
      exists z1 z2,
        clos_refl _ step y1 z1 /\ clos_refl _ step y2 z2 /\ eqv z1 z2.

  Definition steps := clos_refl_trans_1n A step.

  (* The relation "take zero or one step, then move along eqv". *)
  Definition rstep (x y : A) : Prop :=
    exists u, clos_refl _ step x u /\ eqv u y.

  Lemma eqv_sim_refl :
    forall x x' y, eqv x x' -> clos_refl _ step x y ->
      exists y', clos_refl _ step x' y' /\ eqv y y'.
  Proof.
    intros x x' y HE HS. inversion HS; subst.
    - destruct (eqv_sim _ _ _ HE H) as [y' [HS' HE']].
      exists y'; split; auto. now constructor.
    - exists x'; split; auto. apply r_refl.
  Qed.

  Lemma Inv_rstep : forall x y, Inv x -> rstep x y -> Inv y.
  Proof.
    intros x y HI [u [HS HE]].
    inversion HS; subst; eauto.
  Qed.

  Lemma local_diamond_refl :
    forall x y1 y2, Inv x -> clos_refl _ step x y1 -> clos_refl _ step x y2 ->
      exists z1 z2,
        clos_refl _ step y1 z1 /\ clos_refl _ step y2 z2 /\ eqv z1 z2.
  Proof.
    intros x y1 y2 HI H1 H2.
    inversion H1; inversion H2; subst.
    - eauto.
    - exists y1, y1; split; [ apply r_refl | split; [ now constructor | auto ] ].
    - exists y2, y2; split; [ now constructor | split; [ apply r_refl | auto ] ].
    - exists y2, y2; split; [ apply r_refl | split; [ apply r_refl | auto ] ].
  Qed.

  (* [rstep] has the (exact) diamond property. *)
  Lemma rstep_diamond :
    forall x y1 y2, Inv x -> rstep x y1 -> rstep x y2 ->
      exists z, rstep y1 z /\ rstep y2 z.
  Proof.
    intros x y1 y2 HI [u1 [HS1 HE1]] [u2 [HS2 HE2]].
    destruct (local_diamond_refl _ _ _ HI HS1 HS2) as [v1 [v2 [HV1 [HV2 HV]]]].
    destruct (eqv_sim_refl _ _ _ HE1 HV1) as [w1 [HW1 HEW1]].
    destruct (eqv_sim_refl _ _ _ HE2 HV2) as [w2 [HW2 HEW2]].
    exists v2. split.
    - exists w1; split; auto. apply eqv_trans with v1; auto.
    - exists w2; split; auto.
  Qed.

  Definition rsteps := clos_refl_trans_1n A rstep.

  Lemma Inv_rsteps : forall x y, Inv x -> rsteps x y -> Inv y.
  Proof.
    intros x y HI H; induction H; eauto using Inv_rstep.
  Qed.

  (* Strip lemma *)
  Lemma rstep_strip :
    forall x y1 y2, Inv x -> rstep x y1 -> rsteps x y2 ->
      exists z, rsteps y1 z /\ rstep y2 z.
  Proof.
    intros x y1 y2 HI H1 H2. revert y1 H1.
    induction H2; intros.
    - exists y1; split; [ constructor | auto ].
    - destruct (rstep_diamond _ _ _ HI H1 H) as [w [Hw1 Hw2]].
      assert (HIy : Inv y) by eauto using Inv_rstep.
      destruct (IHclos_refl_trans_1n HIy _ Hw2) as [v [Hv1 Hv2]].
      exists v; split; auto. econstructor; eauto.
  Qed.

  Lemma rsteps_confluent :
    forall x y1 y2, Inv x -> rsteps x y1 -> rsteps x y2 ->
      exists z, rsteps y1 z /\ rsteps y2 z.
  Proof.
    intros x y1 y2 HI H1. revert y2. induction H1; intros.
    - exists y2; split; auto. constructor.
    - destruct (rstep_strip _ _ _ HI H H0) as [w [Hw1 Hw2]].
      assert (HIy : Inv y) by eauto using Inv_rstep.
      destruct (IHclos_refl_trans_1n HIy _ Hw1) as [v [Hv1 Hv2]].
      exists v; split; auto. econstructor; eauto.
  Qed.

  Lemma steps_trans : forall x y z, steps x y -> steps y z -> steps x z.
  Proof.
    intros x y z H; revert z; induction H; intros; auto.
    econstructor; eauto. apply IHclos_refl_trans_1n; auto.
  Qed.

  (* eqv is also a simulation for steps *)
  Lemma eqv_sim_steps :
    forall x x' y, eqv x x' -> steps x y ->
      exists y', steps x' y' /\ eqv y y'.
  Proof.
    intros x x' y HE H. revert x' HE. induction H; intros.
    - exists x'; split; auto. constructor.
    - destruct (eqv_sim _ _ _ HE H) as [y' [HS HE']].
      destruct (IHclos_refl_trans_1n _ HE') as [z' [HS' HE'']].
      exists z'; split; auto. econstructor; eauto.
  Qed.

  (* Every rsteps sequence can be done with steps followed by eqv *)
  Lemma rsteps_steps :
    forall x y, rsteps x y -> exists y', steps x y' /\ eqv y' y.
  Proof.
    intros x y H. induction H.
    - exists x; split; auto. constructor.
    - destruct H as [u [HS HE]].
      destruct IHclos_refl_trans_1n as [z' [HZ HEZ]].
      destruct (eqv_sim_steps _ _ _ (eqv_sym _ _ HE) HZ) as [w [HW HEW]].
      exists w; split.
      + inversion HS; subst; auto. econstructor; eauto.
      + apply eqv_trans with z'; auto.
  Qed.

  Lemma steps_rsteps : forall x y, steps x y -> rsteps x y.
  Proof.
    intros x y H; induction H.
    - constructor.
    - econstructor; eauto. exists y; split; auto. now constructor.
  Qed.

  Theorem confluence_modulo :
    forall x y1 y2, Inv x -> steps x y1 -> steps x y2 ->
      exists z1 z2, steps y1 z1 /\ steps y2 z2 /\ eqv z1 z2.
  Proof.
    intros x y1 y2 HI H1 H2.
    apply steps_rsteps in H1, H2.
    destruct (rsteps_confluent _ _ _ HI H1 H2) as [z [Hz1 Hz2]].
    apply rsteps_steps in Hz1 as [z1 [Hz1 HE1]].
    apply rsteps_steps in Hz2 as [z2 [Hz2 HE2]].
    exists z1, z2; repeat split; auto.
    eapply eqv_trans; eauto.
  Qed.

End AbstractConfluence.

Arguments steps {A}.


(* ========================================================================== *)
(* PART 2.  The top-level linear fragment as multiset rewriting               *)
(* ========================================================================== *)

(* At the top level of a bag, a process is (up to ≈p) a multiset of "atoms":
   definitions, applications and equations.  The linear rules (emp cut, tup
   cut, and the three [req] rules) only ever touch two atoms in the top scope
   and replace them with zero, one or two atoms, so we can study them on lists
   of atoms taken up to permutation.  *)

(* -- Atoms, flattening ---------------------------------------------------- *)

Definition is_atom (P : proc) : Prop :=
  match P with
  | par _ _ | nul => False
  | _ => True
  end.

Fixpoint flatten (P : proc) : list proc :=
  match P with
  | par P1 P2 => flatten P1 ++ flatten P2
  | nul => []
  | _ => [P]
  end.

Fixpoint unflatten (l : list proc) : proc :=
  match l with
  | [] => nul
  | P :: l' => par P (unflatten l')
  end.

Lemma flatten_atoms : forall P, Forall is_atom (flatten P).
Proof.
  induction P; simpl; repeat constructor; auto.
  apply Forall_app; split; auto.
Qed.

Lemma flatten_unflatten : forall l, Forall is_atom l -> flatten (unflatten l) = l.
Proof.
  induction l; simpl; intros; auto.
  inversion H; subst. rewrite IHl; auto.
  destruct a; simpl in *; tauto.
Qed.

Lemma unflatten_app : forall l1 l2,
    unflatten (l1 ++ l2) ≈p par (unflatten l1) (unflatten l2).
Proof.
  induction l1; simpl; intros.
  - eapply seq_proc_trans; [ | apply seq_par_comm ]. apply seq_proc_symm, seq_proc_nul.
  - eapply seq_proc_trans; [ | apply seq_par_assoc1 ].
    apply seq_par_cong; auto.
Qed.

Lemma unflatten_flatten : forall P, unflatten (flatten P) ≈p P.
Proof.
  induction P; simpl; try apply seq_proc_nul; try reflexivity.
  eapply seq_proc_trans; [ apply unflatten_app | ].
  apply seq_par_cong; auto.
Qed.

Lemma perm_unflatten : forall l l', Permutation l l' -> unflatten l ≈p unflatten l'.
Proof.
  intros l l' H; induction H; simpl; auto.
  - eapply seq_proc_trans; [ apply seq_par_assoc1 | ].
    eapply seq_proc_trans; [ | apply seq_par_assoc2 ].
    apply seq_par_cong; auto.
  - eapply seq_proc_trans; eauto.
Qed.

(* -- Counting resource-variable occurrences ------------------------------- *)

Definition ind (x v : nat) : nat := if Nat.eqb x v then 1 else 0.
Arguments ind : simpl never.

Lemma ind_refl : forall v, ind v v = 1.
Proof. intros; unfold ind; now rewrite Nat.eqb_refl. Qed.

Lemma ind_neq : forall x v, x <> v -> ind x v = 0.
Proof. intros; unfold ind; destruct (Nat.eqb_spec x v); congruence. Qed.

Definition cnt_oper (v : nat) (o : oper) : nat :=
  match o with
  | tup a b => ind a v + ind b v
  | _ => 0
  end.

Fixpoint cnt_proc (v : nat) (P : proc) : nat :=
  match P with
  | def r o => ind r v + cnt_oper v o
  | app _ r => ind r v
  | req a b => ind a v + ind b v
  | par P1 P2 => cnt_proc v P1 + cnt_proc v P2
  | nul => 0
  end.

Fixpoint cnt (v : nat) (l : list proc) : nat :=
  match l with
  | [] => 0
  | P :: l' => cnt_proc v P + cnt v l'
  end.

Lemma cnt_app : forall v l1 l2, cnt v (l1 ++ l2) = cnt v l1 + cnt v l2.
Proof. induction l1; simpl; intros; auto. rewrite IHl1; lia. Qed.

Lemma cnt_perm : forall v l l', Permutation l l' -> cnt v l = cnt v l'.
Proof. intros v l l' H; induction H; simpl; lia. Qed.

Lemma cnt_flatten : forall v P, cnt v (flatten P) = cnt_proc v P.
Proof.
  induction P; simpl; try lia.
  rewrite cnt_app; lia.
Qed.

(* -- Renaming resource variables, and swaps ------------------------------- *)

Definition rnm (s : nat -> nat) (P : proc) : proc := @rename_rvar_proc 0 0 s P.

Definition swap (a b : nat) : nat -> nat :=
  fun v => if Nat.eqb v a then b else if Nat.eqb v b then a else v.

Lemma swap_invol : forall a b v, swap a b (swap a b v) = v.
Proof.
  intros; unfold swap.
  destruct (Nat.eqb_spec v a); destruct (Nat.eqb_spec v b); subst;
    repeat (match goal with |- context [Nat.eqb ?x ?y] => destruct (Nat.eqb_spec x y) end);
    subst; auto; lia.
Qed.

Lemma swap_ge : forall a b n v, a < n -> b < n -> n <= v -> swap a b v = v.
Proof.
  intros; unfold swap.
  destruct (Nat.eqb_spec v a); destruct (Nat.eqb_spec v b); lia.
Qed.

Lemma swap_lt : forall a b n v, a < n -> b < n -> v < n -> swap a b v < n.
Proof.
  intros; unfold swap.
  destruct (Nat.eqb_spec v a); destruct (Nat.eqb_spec v b); lia.
Qed.

Lemma ind_swap : forall a b x v, ind (swap a b x) v = ind x (swap a b v).
Proof.
  intros. unfold ind.
  destruct (Nat.eqb_spec (swap a b x) v); destruct (Nat.eqb_spec x (swap a b v)); auto.
  - subst. rewrite swap_invol in n. congruence.
  - subst. rewrite swap_invol in n. congruence.
Qed.

Lemma cnt_proc_swap : forall a b v P,
    cnt_proc v (rnm (swap a b) P) = cnt_proc (swap a b v) P.
Proof.
  intros; induction P; unfold rnm in *; simpl; repeat rewrite ind_swap; auto.
  destruct o; simpl; repeat rewrite ind_swap; auto.
Qed.

Lemma cnt_swap : forall a b v l,
    cnt v (map (rnm (swap a b)) l) = cnt (swap a b v) l.
Proof.
  induction l; simpl; auto. rewrite cnt_proc_swap, IHl; auto.
Qed.

Lemma rnm_id_ext : forall s P,
    (forall v, cnt_proc v P > 0 -> s v = v) -> rnm s P = P.
Proof.
  intros s P H. unfold rnm.
  induction P; simpl in *.
  - rewrite H; [ | rewrite ind_refl; lia ].
    destruct o; simpl in *; auto.
    rewrite (H r1), (H r2); auto; rewrite ind_refl; lia.
  - rewrite H; auto. rewrite ind_refl; lia.
  - rewrite (H r1), (H r2); auto; rewrite ind_refl; lia.
  - rewrite IHP1, IHP2; auto; intros; apply H; lia.
  - auto.
Qed.

Lemma map_rnm_id_ext : forall s l,
    (forall v, cnt v l > 0 -> s v = v) -> map (rnm s) l = l.
Proof.
  induction l; simpl; intros; auto.
  rewrite rnm_id_ext, IHl; auto; intros; apply H; lia.
Qed.

Lemma rnm_compose : forall s1 s2 P, rnm s2 (rnm s1 P) = rnm (fun x => s2 (s1 x)) P.
Proof.
  intros; unfold rnm. induction P; simpl; try congruence.
  destruct o; simpl; auto.
Qed.

Lemma rnm_ext : forall s1 s2 P, (forall x, s1 x = s2 x) -> rnm s1 P = rnm s2 P.
Proof.
  intros; unfold rnm. induction P; simpl; try congruence.
  rewrite H. destruct o; simpl; try rewrite H, H; auto.
Qed.

Lemma rnm_swap_invol : forall a b l,
    map (rnm (swap a b)) (map (rnm (swap a b)) l) = l.
Proof.
  induction l; simpl; auto. rewrite IHl, rnm_compose.
  rewrite (rnm_ext _ (fun x => x)); [ | intros; apply swap_invol ].
  f_equal. clear. unfold rnm. induction a0; simpl; try congruence.
  destruct o; simpl; auto.
Qed.

(* -- Atom equivalence ----------------------------------------------------- *)

(* Atoms are equal up to ≈o inside definitions and up to the orientation of
   equations. *)
Inductive atom_eq : proc -> proc -> Prop :=
| ae_refl : forall P, atom_eq P P
| ae_def : forall r o o', o ≈o o' -> atom_eq (def r o) (def r o')
| ae_req : forall a b, atom_eq (req a b) (req b a).

Lemma atom_eq_sym : forall x y, atom_eq x y -> atom_eq y x.
Proof.
  intros x y H; inversion H; subst; constructor; auto. now symmetry.
Qed.

Lemma seq_oper_inv : forall o o', o ≈o o' ->
    o = o' \/ exists t t', o = lam t /\ o' = lam t' /\ t ≈t t'.
Proof.
  intros o o' H; inversion H; subst; eauto 10.
Qed.

(* -- The rules ------------------------------------------------------------ *)

(* [reqv a b x] : x is the equation a = b in either orientation. *)
Inductive reqv (a b : rvar) : proc -> Prop :=
| reqv_l : reqv a b (req a b)
| reqv_r : reqv a b (req b a).

(* The five linear rules of [prim_step], up to orientation of equations. *)
Inductive rule : proc -> proc -> list proc -> Prop :=
| R_emp : forall r, rule (def r emp) (def r emp) nil
| R_tup : forall r a b c d,
    rule (def r (tup a b)) (def r (tup c d)) (req a c :: req b d :: nil)
| R_def : forall a b x o, reqv a b x -> rule x (def a o) (def b o :: nil)
| R_app : forall a b x f, reqv a b x -> rule x (app f a) (app f b :: nil)
| R_req : forall a b c x y, reqv a b x -> reqv a c y -> rule x y (req b c :: nil).

(* The rules are unordered in their two redex atoms. *)
Definition srule x y R := rule x y R \/ rule y x R.

Lemma srule_sym : forall x y R, srule x y R -> srule y x R.
Proof. unfold srule; tauto. Qed.

(* One rewriting step on a multiset of atoms *)
Definition lstep (l l' : list proc) : Prop :=
  exists x y rest R,
    Permutation l (x :: y :: rest) /\ srule x y R /\ l' = R ++ rest.

(* -- The equivalence ------------------------------------------------------ *)

(* [n] is the number of bound resource variables of the scope.  We may
   permute atoms, replace an atom by an equivalent one, and swap two bound
   resource variables. *)
Inductive eqv1 (n : nat) : list proc -> list proc -> Prop :=
| E_perm : forall l l', Permutation l l' -> eqv1 n l l'
| E_atom : forall x x' l, atom_eq x x' -> eqv1 n (x :: l) (x' :: l)
| E_swap : forall a b l, a < n -> b < n -> eqv1 n l (map (rnm (swap a b)) l).

Definition leqv (n : nat) := clos_refl_sym_trans _ (eqv1 n).

Lemma eqv1_sym : forall n l l', eqv1 n l l' -> eqv1 n l' l.
Proof.
  intros n l l' H; inversion H; subst.
  - apply E_perm. now symmetry.
  - apply E_atom. now apply atom_eq_sym.
  - rewrite <- (rnm_swap_invol a b l) at 2. now apply E_swap.
Qed.

Lemma leqv_refl : forall n l, leqv n l l.
Proof. intros; apply rst_refl. Qed.
Lemma leqv_sym : forall n l l', leqv n l l' -> leqv n l' l.
Proof. intros; now apply rst_sym. Qed.
Lemma leqv_trans : forall n l1 l2 l3, leqv n l1 l2 -> leqv n l2 l3 -> leqv n l1 l3.
Proof. intros; eapply rst_trans; eauto. Qed.
Lemma leqv_perm : forall n l l', Permutation l l' -> leqv n l l'.
Proof. intros; apply rst_step; now apply E_perm. Qed.
Lemma leqv_swap : forall n a b l, a < n -> b < n -> leqv n l (map (rnm (swap a b)) l).
Proof. intros; apply rst_step; now apply E_swap. Qed.

Lemma leqv_atom_mid : forall n l1 x x' l2, atom_eq x x' ->
    leqv n (l1 ++ x :: l2) (l1 ++ x' :: l2).
Proof.
  intros.
  eapply leqv_trans; [ apply leqv_perm, Permutation_sym, Permutation_middle | ].
  eapply leqv_trans; [ apply rst_step, E_atom; eauto | ].
  apply leqv_perm, Permutation_middle.
Qed.

Lemma leqv_Forall2_gen : forall n R R', Forall2 atom_eq R R' ->
    forall pre rest, leqv n (pre ++ R ++ rest) (pre ++ R' ++ rest).
Proof.
  intros n R R' H; induction H; simpl; intros.
  - apply leqv_refl.
  - eapply leqv_trans; [ apply leqv_atom_mid; eauto | ].
    replace (pre ++ y :: l ++ rest) with ((pre ++ y :: nil) ++ l ++ rest)
      by (rewrite <- app_assoc; auto).
    replace (pre ++ y :: l' ++ rest) with ((pre ++ y :: nil) ++ l' ++ rest)
      by (rewrite <- app_assoc; auto).
    apply IHForall2.
Qed.

Lemma leqv_Forall2 : forall n R R' rest, Forall2 atom_eq R R' ->
    leqv n (R ++ rest) (R' ++ rest).
Proof. intros. apply (leqv_Forall2_gen n R R' H nil). Qed.

(* -- Well-scopedness facts ------------------------------------------------ *)

Lemma tpo_ws_seq :
  (forall t1 t2, t1 ≈t t2 -> forall m n, ws_term m n t1 <-> ws_term m n t2) /\
  (forall P1 P2, P1 ≈p P2 -> forall m n, ws_proc m n P1 <-> ws_proc m n P2) /\
  (forall o1 o2, o1 ≈o o2 -> forall m n, ws_oper m n o1 <-> ws_oper m n o2).
Proof.
  apply seq_tpo_ind; intros; try tauto.
  - split; intros HW; inversion HW; subst; constructor; apply H; auto.
  - split; intros HW.
    + now inversion HW.
    + repeat constructor; auto.
  - split; intros; apply H; auto.
  - split; intros; [ apply H0, H | apply H, H0 ]; auto.
  - split; intros HW; inversion HW; subst; constructor; auto.
  - split; intros HW; inversion HW; subst;
      [ inversion WSP2 | inversion WSP1 ]; subst; repeat constructor; auto.
  - split; intros HW; inversion HW; subst;
      [ inversion WSP1 | inversion WSP2 ]; subst; repeat constructor; auto.
  - split; intros HW; inversion HW; subst; constructor;
      try (apply H; auto); try (apply H0; auto).
  - split; intros HW; inversion HW; subst; constructor; auto; apply H; auto.
  - split; intros HW; inversion HW; subst; constructor; auto.
  - split; intros HW; inversion HW; subst; constructor; apply H; auto.
Qed.

Lemma ws_seq_proc : forall P1 P2 m n, P1 ≈p P2 -> ws_proc m n P1 -> ws_proc m n P2.
Proof. intros. apply (proj1 (proj2 tpo_ws_seq) P1 P2 H m n); auto. Qed.
Lemma ws_seq_oper : forall o1 o2 m n, o1 ≈o o2 -> ws_oper m n o1 -> ws_oper m n o2.
Proof. intros. apply (proj2 (proj2 tpo_ws_seq) o1 o2 H m n); auto. Qed.

Lemma ws_rnm : forall M N s P, ws_proc M N P -> (forall v, v < N -> s v < N) ->
    ws_proc M N (rnm s P).
Proof.
  intros M N s P HW HS. unfold rnm.
  induction P; inversion HW; subst; simpl; constructor; auto.
  destruct o; inversion WSO; subst; simpl; constructor; auto.
Qed.

Lemma ws_atom_eq : forall M N x x', atom_eq x x' -> ws_proc M N x -> ws_proc M N x'.
Proof.
  intros M N x x' H HW; inversion H; subst; auto.
  - inversion HW; subst; constructor; auto. eapply ws_seq_oper; eauto.
  - inversion HW; subst; constructor; auto.
Qed.

Lemma cnt_atom_eq : forall v x x', atom_eq x x' -> cnt_proc v x = cnt_proc v x'.
Proof.
  intros v x x' H; inversion H; subst; simpl; auto; try lia.
  apply seq_oper_inv in H0 as [ -> | [t [t' [-> [-> _]]]] ]; auto.
Qed.

Lemma is_atom_eq : forall x x', atom_eq x x' -> is_atom x -> is_atom x'.
Proof. intros x x' H; inversion H; subst; simpl; auto. Qed.

(* -- The invariant -------------------------------------------------------- *)

(* [linv M N n l]: the atoms [l] form the body of a bag that binds the first
   [n] of the [N] resource variables in scope.  Every resource variable is
   used at most twice, and the free ones at most once. *)
Definition linv (M N n : nat) (l : list proc) : Prop :=
  n <= N /\
  Forall is_atom l /\
  Forall (ws_proc M N) l /\
  (forall v, cnt v l <= 2) /\
  (forall v, n <= v -> cnt v l <= 1).

Lemma linv_perm : forall M N n l l', Permutation l l' -> linv M N n l -> linv M N n l'.
Proof.
  unfold linv; intros M N n l l' HP (HN & HA & HW & HC & HF).
  repeat split; auto.
  - eapply Permutation_Forall; eauto.
  - eapply Permutation_Forall; eauto.
  - intros; rewrite <- (cnt_perm v _ _ HP); auto.
  - intros; rewrite <- (cnt_perm v _ _ HP); auto.
Qed.

Lemma linv_eqv1 : forall M N n l l', eqv1 n l l' -> linv M N n l -> linv M N n l'.
Proof.
  intros M N n l l' H HI. inversion H; subst.
  - eapply linv_perm; eauto.
  - destruct HI as (HN & HA & HW & HC & HF).
    inversion HA; inversion HW; subst.
    repeat split; auto.
    + constructor; auto. eapply is_atom_eq; eauto.
    + constructor; auto. eapply ws_atom_eq; eauto.
    + intros; specialize (HC v); simpl in *. rewrite <- (cnt_atom_eq v x); auto.
    + intros v Hv; specialize (HF v Hv); simpl in *. rewrite <- (cnt_atom_eq v x); auto.
  - destruct HI as (HN & HA & HW & HC & HF).
    repeat split; auto.
    + apply Forall_map. eapply Forall_impl; [ | apply HA ].
      intros P; destruct P; simpl; auto.
    + apply Forall_map. eapply Forall_impl; [ | apply HW ].
      intros P HP. apply ws_rnm; auto. intros; apply swap_lt with (n := N); lia.
    + intros; rewrite cnt_swap; auto.
    + intros; rewrite cnt_swap. rewrite (swap_ge a b n v); auto.
Qed.

Lemma linv_leqv : forall M N n l l', leqv n l l' -> linv M N n l -> linv M N n l'.
Proof.
  intros M N n l l' H.
  enough (linv M N n l <-> linv M N n l') by tauto.
  induction H; try tauto.
  split; eauto using linv_eqv1, eqv1_sym.
Qed.

Lemma rule_cnt : forall x y R v, rule x y R ->
    cnt v R <= cnt_proc v x + cnt_proc v y.
Proof.
  intros x y R v H; inversion H; subst;
    repeat match goal with H : reqv _ _ _ |- _ => inversion H; subst; clear H end;
    simpl; lia.
Qed.

Lemma rule_atoms : forall x y R, rule x y R -> Forall is_atom R.
Proof.
  intros x y R H; inversion H; subst; repeat constructor.
Qed.

Lemma rule_ws : forall M N x y R, rule x y R -> ws_proc M N x -> ws_proc M N y ->
    Forall (ws_proc M N) R.
Proof.
  intros M N x y R H HX HY; inversion H; subst;
    repeat match goal with H : reqv _ _ _ |- _ => inversion H; subst; clear H end;
    repeat match goal with
           | H : ws_proc _ _ (def _ _) |- _ => inversion H; subst; clear H
           | H : ws_proc _ _ (req _ _) |- _ => inversion H; subst; clear H
           | H : ws_proc _ _ (app _ _) |- _ => inversion H; subst; clear H
           | H : ws_oper _ _ (tup _ _) |- _ => inversion H; subst; clear H
           end;
    repeat constructor; auto.
Qed.

Lemma linv_lstep : forall M N n l l', lstep l l' -> linv M N n l -> linv M N n l'.
Proof.
  intros M N n l l' (x & y & rest & R & HP & HR & ->) HI.
  apply (linv_perm _ _ _ _ _ HP) in HI.
  destruct HI as (HN & HA & HW & HC & HF).
  inversion HA as [ | ? ? HAx HA' ]; inversion HA' as [ | ? ? HAy HArest ]; subst.
  inversion HW as [ | ? ? HWx HW' ]; inversion HW' as [ | ? ? HWy HWrest ]; subst.
  assert (HC' : forall v, cnt v R <= cnt_proc v x + cnt_proc v y).
  { intros v; destruct HR as [HR | HR]; pose proof (rule_cnt _ _ _ v HR); lia. }
  repeat split; auto.
  - apply Forall_app; split; auto. destruct HR; eapply rule_atoms; eauto.
  - apply Forall_app; split; auto. destruct HR; eapply rule_ws; eauto.
  - intros v; specialize (HC v); specialize (HC' v); simpl in HC.
    rewrite cnt_app; lia.
  - intros v Hv; specialize (HF v Hv); specialize (HC' v); simpl in HF.
    rewrite cnt_app; lia.
Qed.

(* -- Permutation case analysis -------------------------------------------- *)

Lemma perm_cons_split : forall {A} (a : A) l L,
    Permutation (a :: l) L ->
    exists L1 L2, L = L1 ++ a :: L2 /\ Permutation l (L1 ++ L2).
Proof.
  intros A a l L HP.
  assert (In a L) by (eapply Permutation_in; eauto; left; auto).
  apply in_split in H as (L1 & L2 & ->).
  exists L1, L2; split; auto.
  eapply Permutation_cons_app_inv; eauto.
Qed.

(* Two ways of picking a pair out of the same multiset either pick disjoint
   pairs, share exactly one element, or pick the same pair. *)
Lemma perm_2_2 : forall {A} (x1 y1 x2 y2 : A) r1 r2,
    Permutation (x1 :: y1 :: r1) (x2 :: y2 :: r2) ->
    (exists r, Permutation r1 (x2 :: y2 :: r) /\ Permutation r2 (x1 :: y1 :: r))
    \/ (exists a b1 b2 r,
          ((x1 = a /\ y1 = b1) \/ (x1 = b1 /\ y1 = a)) /\
          ((x2 = a /\ y2 = b2) \/ (x2 = b2 /\ y2 = a)) /\
          Permutation r1 (b2 :: r) /\ Permutation r2 (b1 :: r))
    \/ (((x1 = x2 /\ y1 = y2) \/ (x1 = y2 /\ y1 = x2)) /\ Permutation r1 r2).
Proof.
  intros A x1 y1 x2 y2 r1 r2 HP.
  apply perm_cons_split in HP as (L1 & L2 & HL & HP).
  destruct L1 as [ | u [ | v L1 ] ]; simpl in HL.
  - (* x1 = x2 *)
    injection HL as -> <-.
    apply perm_cons_split in HP as (K1 & K2 & HK & HP).
    destruct K1 as [ | w K1 ]; simpl in HK.
    + injection HK as -> ->. right; right. split; auto.
    + injection HK as -> ->. right; left. exists x1, y1, w, (K1 ++ K2).
      repeat split; auto. apply Permutation_sym, Permutation_middle.
  - (* x1 = y2 *)
    injection HL as -> -> <-.
    apply perm_cons_split in HP as (K1 & K2 & HK & HP).
    destruct K1 as [ | w K1 ]; simpl in HK.
    + injection HK as -> ->. right; right. split; auto.
    + injection HK as -> ->. right; left. exists x1, y1, w, (K1 ++ K2).
      repeat split; auto. apply Permutation_sym, Permutation_middle.
  - (* x1 in r2 *)
    injection HL as -> -> ->.
    apply perm_cons_split in HP as (K1 & K2 & HK & HP).
    destruct K1 as [ | w [ | w' K1 ] ]; simpl in HK.
    + injection HK as -> <-. right; left. exists y1, x1, v, (L1 ++ L2).
      repeat split; auto. apply Permutation_sym, Permutation_middle.
    + injection HK as -> -> <-. right; left. exists y1, x1, w, (L1 ++ L2).
      repeat split; auto. apply Permutation_sym, Permutation_middle.
    + injection HK as -> -> HK. left. exists (K1 ++ K2). split; auto.
      eapply perm_trans; [ apply Permutation_sym, Permutation_middle | ].
      constructor. rewrite HK. apply Permutation_sym, Permutation_middle.
Qed.

(* -- The rules are compatible with the equivalence ------------------------ *)

Lemma reqv_flip : forall a b x y, reqv a b (req x y) -> reqv a b (req y x).
Proof. intros a b x y H; inversion H; subst; constructor. Qed.

Lemma reqv_rnm : forall s a b x, reqv a b x -> reqv (s a) (s b) (rnm s x).
Proof. intros s a b x H; inversion H; subst; constructor. Qed.

Lemma rule_rnm : forall s x y R, rule x y R ->
    rule (rnm s x) (rnm s y) (map (rnm s) R).
Proof.
  intros s x y R H; inversion H; subst; simpl.
  - constructor.
  - constructor.
  - apply (R_def (s a) (s b)); auto using reqv_rnm.
  - apply (R_app (s a) (s b)); auto using reqv_rnm.
  - apply (R_req (s a) (s b) (s c)); auto using reqv_rnm.
Qed.

Lemma srule_rnm : forall s x y R, srule x y R ->
    srule (rnm s x) (rnm s y) (map (rnm s) R).
Proof. intros s x y R [H|H]; [left|right]; auto using rule_rnm. Qed.

Ltac inv_reqv :=
  repeat match goal with H : reqv _ _ _ |- _ => inversion H; subst; clear H end.

Lemma Forall2_ae_refl : forall R, Forall2 atom_eq R R.
Proof. induction R; constructor; auto using ae_refl. Qed.

Lemma rule_ae_l : forall x x' y R, atom_eq x x' -> rule x y R ->
    exists R', rule x' y R' /\ Forall2 atom_eq R R'.
Proof.
  intros x x' y R HE HR.
  assert (HRef : Forall2 atom_eq R R) by apply Forall2_ae_refl.
  inversion HE; subst; eauto.
  - inversion HR; subst; inv_reqv;
      apply seq_oper_inv in H as [ <- | [t [t' [? [? ?]]]] ]; try discriminate; eauto.
  - inversion HR; subst; inv_reqv; eexists; split; eauto;
      econstructor; eauto using reqv_flip; constructor.
Qed.

Lemma rule_ae_r : forall x y y' R, atom_eq y y' -> rule x y R ->
    exists R', rule x y' R' /\ Forall2 atom_eq R R'.
Proof.
  intros x y y' R HE HR.
  assert (HRef : Forall2 atom_eq R R) by apply Forall2_ae_refl.
  inversion HE; subst; eauto.
  - pose proof H as Hs.
    inversion HR; subst; inv_reqv;
      try (apply seq_oper_inv in H as [ <- | [t [t' [? [? ?]]]] ]; try discriminate; eauto).
    all: eexists; split; [ econstructor; eauto using reqv_flip | ].
    all: repeat constructor; auto.
  - inversion HR; subst; inv_reqv; eexists; split; eauto;
      econstructor; eauto using reqv_flip; constructor.
Qed.

Lemma srule_ae_l : forall x x' y R, atom_eq x x' -> srule x y R ->
    exists R', srule x' y R' /\ Forall2 atom_eq R R'.
Proof.
  intros x x' y R HE [HR | HR].
  - destruct (rule_ae_l _ _ _ _ HE HR) as [R' [? ?]]; exists R'; split; auto; now left.
  - destruct (rule_ae_r _ _ _ _ HE HR) as [R' [? ?]]; exists R'; split; auto; now right.
Qed.

Lemma srule_ae_r : forall x y y' R, atom_eq y y' -> srule x y R ->
    exists R', srule x y' R' /\ Forall2 atom_eq R R'.
Proof.
  intros x y y' R HE HR. apply srule_sym in HR.
  destruct (srule_ae_l _ _ _ _ HE HR) as [R' [? ?]].
  exists R'; split; auto. now apply srule_sym.
Qed.

(* -- Simulation: the equivalence commutes with lstep ---------------------- *)

Lemma lstep_perm : forall l l' l1, Permutation l l' -> lstep l l1 -> lstep l' l1.
Proof.
  intros l l' l1 HP (x & y & rest & R & HP' & HR & ->).
  exists x, y, rest, R; repeat split; auto.
  eapply perm_trans; [ apply Permutation_sym; eauto | auto ].
Qed.

Lemma eqv1_sim : forall n l l' l1, eqv1 n l l' -> lstep l l1 ->
    exists l1', lstep l' l1' /\ leqv n l1 l1'.
Proof.
  intros n l l' l1 HE HS. inversion HE; subst.
  - exists l1; split; [ eapply lstep_perm; eauto | apply leqv_refl ].
  - destruct HS as (x0 & y0 & rest & R & HP & HR & ->).
    apply perm_cons_split in HP as (L1 & L2 & HL & HP).
    destruct L1 as [ | u [ | v L1 ] ]; simpl in HL; injection HL; intros; subst.
    + destruct (srule_ae_l _ _ _ _ H HR) as [R' [HR' HF]].
      exists (R' ++ rest); split.
      * exists x', y0, rest, R'; repeat split; auto.
      * now apply leqv_Forall2.
    + destruct (srule_ae_r _ _ _ _ H HR) as [R' [HR' HF]].
      exists (R' ++ L2); split.
      * exists u, x', L2, R'; repeat split; auto.
        eapply perm_trans; [ apply perm_skip; eauto | apply perm_swap ].
      * now apply leqv_Forall2.
    + exists (R ++ L1 ++ x' :: L2); split.
      * exists u, v, (L1 ++ x' :: L2), R; repeat split; auto.
        eapply perm_trans; [ apply perm_skip; eauto | ].
        simpl. eapply perm_trans; [ apply perm_swap | ].
        apply perm_skip. eapply perm_trans; [ apply perm_swap | ].
        apply perm_skip. apply Permutation_middle.
      * rewrite !app_assoc. now apply leqv_atom_mid.
  - destruct HS as (x & y & rest & R & HP & HR & ->).
    exists (map (rnm (swap a b)) (R ++ rest)); split.
    + exists (rnm (swap a b) x), (rnm (swap a b) y), (map (rnm (swap a b)) rest),
        (map (rnm (swap a b)) R).
      repeat split; auto using srule_rnm.
      * apply (Permutation_map (rnm (swap a b))) in HP. auto.
      * now rewrite map_app.
    + now apply leqv_swap.
Qed.

Lemma leqv_sim : forall n l l' l1, leqv n l l' -> lstep l l1 ->
    exists l1', lstep l' l1' /\ leqv n l1 l1'.
Proof.
  intros n l l' l1 H. revert l1.
  enough ((forall l1, lstep l l1 -> exists l1', lstep l' l1' /\ leqv n l1 l1') /\
          (forall l1', lstep l' l1' -> exists l1, lstep l l1 /\ leqv n l1' l1)) by tauto.
  induction H.
  - split; intros; eapply eqv1_sim; eauto using eqv1_sym.
  - split; intros; eexists; split; eauto using leqv_refl.
  - tauto.
  - destruct IHclos_refl_sym_trans1 as [A1 B1], IHclos_refl_sym_trans2 as [A2 B2].
    split; intros.
    + destruct (A1 _ H1) as [u [Hu Eu]]. destruct (A2 _ Hu) as [w [Hw Ew]].
      exists w; split; eauto using leqv_trans.
    + destruct (B2 _ H1) as [u [Hu Eu]]. destruct (B1 _ Hu) as [w [Hw Ew]].
      exists w; split; eauto using leqv_trans.
Qed.

(* -- Critical pairs ------------------------------------------------------- *)

(* Derive a contradiction from some variable being used three times. *)
Ltac cnt_contra HC :=
  match goal with
  | v : rvar |- _ =>
      let H := fresh in pose proof (HC v) as H; simpl in H;
      rewrite ?ind_refl in H; lia
  | v : nat |- _ =>
      let H := fresh in pose proof (HC v) as H; simpl in H;
      rewrite ?ind_refl in H; lia
  end.

Lemma leqv_2 : forall n x y x' y' r, atom_eq x x' -> atom_eq y y' ->
    leqv n (x :: y :: r) (x' :: y' :: r).
Proof.
  intros. apply (leqv_Forall2 n (x :: y :: nil) (x' :: y' :: nil)).
  repeat constructor; auto.
Qed.

Lemma leqv_2s : forall n x y x' y' r, atom_eq x y' -> atom_eq y x' ->
    leqv n (x :: y :: r) (x' :: y' :: r).
Proof.
  intros. eapply leqv_trans; [ apply leqv_perm, perm_swap | ].
  apply leqv_2; auto.
Qed.

Ltac solve_ae := first [ apply ae_refl | apply ae_req ].

Lemma leqv_1 : forall n x x' r, atom_eq x x' -> leqv n (x :: r) (x' :: r).
Proof. intros. apply rst_step, E_atom; auto. Qed.

Ltac solve_leqv_small :=
  first [ apply leqv_refl
        | apply leqv_1; solve_ae
        | apply leqv_2; solve_ae
        | apply leqv_2s; solve_ae ].

Lemma oper_rnm_id : forall s o,
    (forall v, cnt_oper v o > 0 -> s v = v) -> @rename_rvar_oper 0 0 s o = o.
Proof.
  intros s o H; destruct o; simpl in *; auto.
  rewrite (H r1), (H r2); auto; rewrite ind_refl; lia.
Qed.

(* Close a goal  leqv n L R  where R becomes L (up to order and orientation)
   after swapping p and q. *)
Ltac close_by_swap HC HF p q :=
  let Hp := fresh in let Hq := fresh in
  match goal with |- leqv ?n _ _ =>
  assert (Hp : p < n) by
    (destruct (lt_dec p n) as [ | Hn ]; auto; exfalso;
     assert (n <= p) by lia; pose proof (HF p ltac:(lia)) as Hx; simpl in Hx;
     rewrite ?ind_refl in Hx; lia);
  assert (Hq : q < n) by
    (destruct (lt_dec q n) as [ | Hn ]; auto; exfalso;
     assert (n <= q) by lia; pose proof (HF q ltac:(lia)) as Hx; simpl in Hx;
     rewrite ?ind_refl in Hx; lia);
  match goal with |- leqv _ _ ?R =>
    apply leqv_trans with (map (rnm (swap p q)) R);
    [ | apply leqv_sym, leqv_swap; auto ] end;
  simpl map;
  match goal with |- context [map (rnm (swap p q)) ?r] =>
    rewrite (map_rnm_id_ext (swap p q) r);
    [ | let v := fresh in let Hv := fresh in
        intros v Hv; unfold swap;
        destruct (Nat.eqb_spec v p);
        [ subst; pose proof (HC p) as Hx; simpl in Hx; rewrite ?ind_refl in Hx; lia | ];
        destruct (Nat.eqb_spec v q);
        [ subst; pose proof (HC q) as Hx; simpl in Hx; rewrite ?ind_refl in Hx; lia | ];
        auto ]
  end;
  unfold rnm; simpl;
  idtac end;
  repeat match goal with
  | |- context [ @rename_rvar_oper _ _ (swap p q) ?o ] =>
      rewrite (oper_rnm_id (swap p q) o);
      [ | let v := fresh in let Hv := fresh in
          intros v Hv; unfold swap;
          destruct (Nat.eqb_spec v p);
          [ subst; pose proof (HC p) as Hx; simpl in Hx; rewrite ?ind_refl in Hx; lia | ];
          destruct (Nat.eqb_spec v q);
          [ subst; pose proof (HC q) as Hx; simpl in Hx; rewrite ?ind_refl in Hx; lia | ];
          auto ]
  end;
  unfold swap;
  repeat match goal with
  | |- context [Nat.eqb ?x ?y] =>
      destruct (Nat.eqb_spec x y); subst; try (exfalso; cnt_contra HC)
  end;
  solve_leqv_small.

Ltac close_by_swap_auto HC HF :=
  match type of HC with
  | forall v, cnt v (req ?p ?q :: _) <= 2 => close_by_swap HC HF p q
  | forall v, cnt v (_ :: req ?p ?q :: _) <= 2 => close_by_swap HC HF p q
  end.

Lemma share_one : forall M N n a b1 b2 r R1 R2,
    linv M N n (a :: b1 :: b2 :: r) -> srule a b1 R1 -> srule a b2 R2 ->
    leqv n (R1 ++ b2 :: r) (R2 ++ b1 :: r).
Proof.
  intros M N n a b1 b2 r R1 R2 (HN & HA & HW & HC & HF) H1 H2.
  destruct H1 as [H1|H1]; destruct H2 as [H2|H2];
  inversion H1; subst; inv_reqv; inversion H2; subst; inv_reqv;
  try (exfalso; cnt_contra HC).
  all: close_by_swap_auto HC HF.
Qed.

Lemma share_two : forall M N n x y r R1 R2,
    linv M N n (x :: y :: r) -> srule x y R1 -> srule x y R2 ->
    leqv n (R1 ++ r) (R2 ++ r).
Proof.
  intros M N n x y r R1 R2 (HN & HA & HW & HC & HF) H1 H2.
  destruct H1 as [H1|H1]; destruct H2 as [H2|H2];
  inversion H1; subst; inv_reqv; inversion H2; subst; inv_reqv;
  try (exfalso; cnt_contra HC).
  all: simpl; try solve_leqv_small.
  all: close_by_swap_auto HC HF.
Qed.

(* -- The local diamond ---------------------------------------------------- *)

Lemma ldiamond : forall M N n l l1 l2,
    linv M N n l -> lstep l l1 -> lstep l l2 ->
    exists l3 l4, clos_refl _ lstep l1 l3 /\ clos_refl _ lstep l2 l4 /\ leqv n l3 l4.
Proof.
  intros M N n l l1 l2 HI (x1 & y1 & r1 & R1 & HP1 & HR1 & ->)
    (x2 & y2 & r2 & R2 & HP2 & HR2 & ->).
  assert (HP : Permutation (x1 :: y1 :: r1) (x2 :: y2 :: r2))
    by (eapply perm_trans; [ apply Permutation_sym; eauto | eauto ]).
  apply (linv_perm _ _ _ _ _ HP1) in HI.
  destruct (perm_2_2 _ _ _ _ _ _ HP)
    as [ (r & Hr1 & Hr2) | [ (a & b1 & b2 & r & E1 & E2 & Hr1 & Hr2) | (E & Hr) ] ].
  - (* disjoint redexes commute *)
    exists (R2 ++ R1 ++ r), (R1 ++ R2 ++ r). repeat split.
    + apply r_step. exists x2, y2, (R1 ++ r), R2. repeat split; auto.
      rewrite Hr1, <- !Permutation_middle. reflexivity.
    + apply r_step. exists x1, y1, (R2 ++ r), R1. repeat split; auto.
      rewrite Hr2, <- !Permutation_middle. reflexivity.
    + apply leqv_perm, Permutation_app_swap_app.
  - (* one shared atom *)
    assert (HS1 : srule a b1 R1)
      by (destruct E1 as [[-> ->] | [-> ->]]; auto using srule_sym).
    assert (HS2 : srule a b2 R2)
      by (destruct E2 as [[-> ->] | [-> ->]]; auto using srule_sym).
    assert (HI' : linv M N n (a :: b1 :: b2 :: r)).
    { eapply linv_perm; [ | apply HI ].
      destruct E1 as [[-> ->] | [-> ->]]; rewrite Hr1; [ | apply perm_swap ]; auto. }
    exists (R1 ++ r1), (R2 ++ r2); repeat split; try apply r_refl.
    eapply leqv_trans; [ apply leqv_perm, Permutation_app_head, Hr1 | ].
    eapply leqv_trans; [ eapply share_one; eauto | ].
    apply leqv_perm, Permutation_app_head, Permutation_sym, Hr2.
  - (* the same two atoms *)
    assert (HS2 : srule x1 y1 R2)
      by (destruct E as [[-> ->] | [-> ->]]; auto using srule_sym).
    exists (R1 ++ r1), (R2 ++ r2); repeat split; try apply r_refl.
    eapply leqv_trans; [ eapply share_two; eauto | ].
    apply leqv_perm, Permutation_app_head, Hr.
Qed.

(* -- Confluence of the multiset model ------------------------------------- *)

Theorem lstep_confluence : forall M N n l l1 l2,
    linv M N n l -> steps lstep l l1 -> steps lstep l l2 ->
    exists l3 l4, steps lstep l1 l3 /\ steps lstep l2 l4 /\ leqv n l3 l4.
Proof.
  intros M N n.
  apply (confluence_modulo (list proc) lstep (leqv n) (linv M N n)).
  - apply leqv_refl.
  - apply leqv_sym.
  - apply leqv_trans.
  - intros; eapply linv_lstep; eauto.
  - intros; eapply linv_leqv; eauto.
  - intros; eapply leqv_sim; eauto.
  - intros; eapply ldiamond; eauto.
Qed.


