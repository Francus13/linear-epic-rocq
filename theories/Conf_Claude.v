(* OVERVIEW

   Nothing in this file is Admitted.  The only axiom used is functional
   extensionality (already used by Contexts.v).  It depends on Contexts,
   Syntax, EvalContexts and Semantics, but not on Preservation, which does
   not currently build.

   PART 1  Abstract rewriting.  [confluence_modulo]: if an equivalence ~ is
           a simulation for -> and -> has a local diamond modulo ~ (each
           side taking 0 or 1 steps), then -> is confluent modulo ~.

   PART 2  A model of the top scope of a bag as a multiset (list up to
           permutation) of atoms (defs, apps, reqs).  [lstep] applies the
           five linear rules (emp cut, tup cut, req_def, req_app, req_req).
           [leqv] = permutation + ≈ on atoms + swapping two bound resource
           variables.  Critical pairs are analysed by counting variable
           occurrences (linearity: each resource variable occurs at most
           twice, free ones at most once):
             - two redexes sharing one atom must share an equation r1 = r2,
               and the two results differ by swapping r1 and r2
               ([share_one]);
             - everything else commutes or is a contradiction with the
               occurrence counts.
           [lstep_confluence]: lstep is confluent modulo leqv.

   PART 3  The link with LinOpal's semantics.  [top_lin_prim_step] is the
           linear part of [prim_step] at evaluation contexts whose hole is
           not under a lambda; [top_lin_step] is it up to ≈t (a sub-relation
           of [step]).  Both directions of the simulation between terms and
           atom multisets are proven.
           MAIN THEOREM [top_linear_confluence]:
             wf_term m0 n0 t -> t ->* t1 -> t ->* t2 ->
             exists t3 t4, t1 ->* t3, t2 ->* t4, and t3, t4 are related by
             the equivalence generated by ≈t and nu-equivalence ([t≡ ]).

   PART 4  Confluence up to bisimulation for the full [step].  Defines
           observation-respecting bisimilarity, proves it is an equivalence
           and a simulation, and proves two general routes to confluence up
           to bisimilarity: a local diamond ([confluence_up_to_bisim_local])
           or, when steps duplicate redexes, a diamond for a parallel step
           ([confluence_up_to_bisim_parallel]).  Proves that ≈t is a
           bisimulation for the full [step] ([seq_bisimilar]), and states
           the target theorem [LinOpal_confluent_up_to_bisim] (a definition,
           not yet proven).  See the closing comment for the plan.

   ABOUT THE OUTLINE IN Confluence.v.  Its step 1 ("strong confluence of
   top-level steps, up to alpha") holds for the linear rules, as proven
   here, but only with "each side takes 0 or 1 steps": when the two redexes
   share an equation r1 = r2, the two results are already alpha-equivalent
   (swap r1, r2) and may be normal forms, so "t1 -> t' and t2 -> t'" with
   one step each is too strong.  The lemma [no_strong_confluence] uses the
   old par-nul rule, which is now folded into ≈t ([seq_proc_nul]), so its
   counterexample no longer applies as written.
*)

