(* -- The top-level linear fragment of prim_step --------------------------- *)

(* The linear rules of [prim_step], restricted to evaluation contexts whose
   hole is in the top scope (not under a lambda). *)
Inductive top_lin_prim_step : term -> term -> Prop :=
| tl_emp_cut : forall Et r,
    is_hole_scope_at_top Et = true ->
    top_lin_prim_step (Et <=[ par (def r emp) (def r emp) ]) (Et <=[ nul ])
| tl_tup_cut : forall Et r r1 r2 r1' r2',
    is_hole_scope_at_top Et = true ->
    top_lin_prim_step
      (Et <=[ par (def r (tup r1 r2)) (def r (tup r1' r2')) ])
      (Et <=[ par (req r1 r1') (req r2 r2') ])
| tl_req_def : forall Et r1 r2 o,
    is_hole_scope_at_top Et = true ->
    top_lin_prim_step (Et <=[ par (req r1 r2) (def r1 o) ]) (Et <=[ def r2 o ])
| tl_req_app : forall Et r1 r2 f,
    is_hole_scope_at_top Et = true ->
    top_lin_prim_step (Et <=[ par (req r1 r2) (app f r1) ]) (Et <=[ app f r2 ])
| tl_req_req : forall Et r1 r2 r,
    is_hole_scope_at_top Et = true ->
    top_lin_prim_step (Et <=[ par (req r1 r2) (req r1 r) ]) (Et <=[ req r2 r ]).

Lemma top_lin_prim_step_prim_step : forall t t',
    top_lin_prim_step t t' -> prim_step t t'.
Proof. intros t t' H; inversion H; subst; constructor. Qed.

(* Like [step], the top-level linear steps work up to ≈t on the left. *)
Definition top_lin_step (t t' : term) : Prop :=
  exists t0, t ≈t t0 /\ top_lin_prim_step t0 t'.

Lemma top_lin_step_step : forall t t', top_lin_step t t' -> step t t'.
Proof.
  intros t t' (t0 & HE & HS). econstructor; eauto.
  now apply top_lin_prim_step_prim_step.
Qed.

Definition top_lin_steps := clos_refl_trans_1n term top_lin_step.

Lemma top_lin_steps_multi_step : forall t t',
    top_lin_steps t t' -> multi_step t t'.
Proof.
  intros t t' H; induction H; econstructor; eauto using top_lin_step_step.
Qed.

(* -- Flattening respects structural equivalence --------------------------- *)

(* The equivalence on atom lists without swaps; it is a congruence for ++. *)
Inductive peqv1 : list proc -> list proc -> Prop :=
| P_perm : forall l l', Permutation l l' -> peqv1 l l'
| P_atom : forall x x' l1 l2, atom_eq x x' -> peqv1 (l1 ++ x :: l2) (l1 ++ x' :: l2).

Definition peqv := clos_refl_sym_trans _ peqv1.

Lemma peqv1_app_l : forall k l l', peqv1 l l' -> peqv1 (k ++ l) (k ++ l').
Proof.
  intros k l l' H; inversion H; subst.
  - apply P_perm. now apply Permutation_app_head.
  - rewrite !app_assoc. now apply P_atom.
Qed.

Lemma peqv1_app_r : forall k l l', peqv1 l l' -> peqv1 (l ++ k) (l' ++ k).
Proof.
  intros k l l' H; inversion H; subst.
  - apply P_perm. now apply Permutation_app_tail.
  - rewrite <- !app_assoc. simpl. now apply P_atom.
Qed.

Lemma peqv_app : forall l1 l1' l2 l2', peqv l1 l1' -> peqv l2 l2' ->
    peqv (l1 ++ l2) (l1' ++ l2').
Proof.
  intros l1 l1' l2 l2' H1 H2.
  apply rst_trans with (l1' ++ l2).
  - clear H2. induction H1.
    + apply rst_step. now apply peqv1_app_r.
    + apply rst_refl.
    + now apply rst_sym.
    + eapply rst_trans; eauto.
  - clear H1. induction H2.
    + apply rst_step. now apply peqv1_app_l.
    + apply rst_refl.
    + now apply rst_sym.
    + eapply rst_trans; eauto.
Qed.

Lemma peqv_leqv : forall n l l', peqv l l' -> leqv n l l'.
Proof.
  intros n l l' H; induction H.
  - inversion H; subst; [ now apply leqv_perm | now apply leqv_atom_mid ].
  - apply leqv_refl.
  - now apply leqv_sym.
  - eapply leqv_trans; eauto.
Qed.

Lemma seq_flatten : forall P Q, P ≈p Q -> peqv (flatten P) (flatten Q).
Proof.
  intros P Q H; induction H; simpl.
  - apply rst_refl.
  - rewrite app_nil_r. apply rst_refl.
  - now apply rst_sym.
  - eapply rst_trans; eauto.
  - apply rst_step, P_perm, Permutation_app_comm.
  - rewrite app_assoc. apply rst_refl.
  - rewrite app_assoc. apply rst_refl.
  - now apply peqv_app.
  - apply rst_step. apply (P_atom (def r o1) (def r o2) nil nil). now constructor.
  - apply rst_step. apply (P_atom (req r1 r2) (req r2 r1) nil nil). constructor.
Qed.

(* -- Filling a top-level evaluation context ------------------------------- *)

Fixpoint ctx_flat (EP : EC_proc) : list proc :=
  match EP with
  | Ehol => nil
  | Edeflam _ _ => nil
  | Epar EP' P => ctx_flat EP' ++ flatten P
  end.

Lemma flatten_fill_top : forall EP Q,
    is_hole_scope_at_top_proc EP = true ->
    flatten (EP <=[ Q ]p) = flatten Q ++ ctx_flat EP.
Proof.
  induction EP; simpl; intros; try discriminate.
  - now rewrite app_nil_r.
  - rewrite IHEP; auto. now rewrite app_assoc.
Qed.

(* Every top-level linear prim_step is an lstep of the flattened body. *)
Lemma top_lin_prim_lstep : forall t0 t1, top_lin_prim_step t0 t1 ->
    exists m n P0 P1, t0 = bag m n P0 /\ t1 = bag m n P1 /\
      lstep (flatten P0) (flatten P1).
Proof.
  intros t0 t1 H.
  inversion H; subst; destruct Et as [m n EP]; simpl in *;
    eexists m, n, _, _; repeat split;
    rewrite !flatten_fill_top; auto; simpl;
    eexists _, _, (ctx_flat EP), _;
    (split; [ apply Permutation_refl
            | split; [ left; econstructor; constructor | reflexivity ] ]).
Qed.

(* Every lstep of the flattened body is a top-level linear step. *)

Definition refold (R : list proc) : proc :=
  match R with
  | nil => nul
  | z :: nil => z
  | z1 :: z2 :: _ => par z1 z2
  end.

Ltac flipp P :=
  match P with
  | req ?a ?b => constr:(req b a)
  | _ => constr:(P)
  end.

Ltac solve_redex_body :=
  split; [ apply seq_par_cong; first [ reflexivity | apply seq_req_comm ]
         | split; [ reflexivity | intros; constructor; auto ] ].

Ltac solve_redex :=
  match goal with |- exists Q Q', par ?x ?y ≈p Q /\ flatten Q' = ?R /\ _ =>
    let fx := flipp x in let fy := flipp y in
    first [ exists (par x y), (refold R); solve_redex_body
          | exists (par fx y), (refold R); solve_redex_body
          | exists (par x fy), (refold R); solve_redex_body
          | exists (par fx fy), (refold R); solve_redex_body ]
  end.

Lemma rule_redex : forall x y R, rule x y R ->
    exists Q Q', par x y ≈p Q /\ flatten Q' = R /\
      forall Et, is_hole_scope_at_top Et = true ->
        top_lin_prim_step (Et <=[ Q ]) (Et <=[ Q' ]).
Proof.
  intros x y R H; inversion H; subst; inv_reqv; solve_redex.
Qed.

Lemma srule_redex : forall x y R, srule x y R ->
    exists Q Q', par x y ≈p Q /\ flatten Q' = R /\
      forall Et, is_hole_scope_at_top Et = true ->
        top_lin_prim_step (Et <=[ Q ]) (Et <=[ Q' ]).
Proof.
  intros x y R [HR | HR]; [ now apply rule_redex | ].
  destruct (rule_redex _ _ _ HR) as (Q & Q' & HQ & HQ' & HS).
  exists Q, Q'; repeat split; auto.
  eapply seq_proc_trans; [ apply seq_par_comm | eauto ].
Qed.

Lemma lstep_top_lin : forall m n P l1, lstep (flatten P) l1 ->
    exists P1, top_lin_step (bag m n P) (bag m n P1) /\ flatten P1 = l1.
Proof.
  intros m n P l1 (x & y & rest & R & HP & HR & ->).
  destruct (srule_redex _ _ _ HR) as (Q & Q' & HQ & HQ' & HS).
  exists (par Q' (unflatten rest)). split.
  - exists (Ebag m n (Epar Ehol (unflatten rest)) <=[ Q ]). split.
    + simpl. constructor.
      eapply seq_proc_trans; [ apply seq_proc_symm, unflatten_flatten | ].
      eapply seq_proc_trans; [ apply perm_unflatten, HP | ]. simpl.
      eapply seq_proc_trans; [ apply seq_par_assoc1 | ].
      apply seq_par_cong; auto.
    + apply (HS (Ebag m n (Epar Ehol (unflatten rest)))). reflexivity.
  - simpl. rewrite HQ', flatten_unflatten; auto.
    assert (HA : Forall is_atom (x :: y :: rest))
      by (eapply Permutation_Forall; [ apply HP | apply flatten_atoms ]).
    apply Forall_inv_tail, Forall_inv_tail in HA; auto.
Qed.

(* -- Well-formed terms satisfy the invariant ------------------------------ *)

Lemma ws_flatten : forall M N P, ws_proc M N P -> Forall (ws_proc M N) (flatten P).
Proof.
  intros M N P H; induction P; inversion H; subst; simpl; repeat constructor; auto.
  apply Forall_app; split; auto.
Qed.

Ltac solve_cnt :=
  unfold ind, sum, one, delta, zero, flat_ctxt in *;
  repeat match goal with
         | |- context [lt_dec ?a ?b] => destruct (lt_dec a b)
         | |- context [Nat.eq_dec ?a ?b] => destruct (Nat.eq_dec a b)
         | |- context [Nat.eqb ?a ?b] => destruct (Nat.eqb_spec a b)
         end; subst; try lia.

Lemma wf_cnt : forall M N G D P, wf_proc M N G D P ->
    forall v, v < N -> cnt_proc v P = D v.
Proof.
  intros M N G D P. revert G D.
  induction P; intros G D H v Hv; inversion H; existT_eq; subst; simpl.
  - rewrite (HD v Hv). unfold sum.
    destruct o; inversion WFO; existT_eq; subst; simpl;
      try rewrite (HD0 v Hv); solve_cnt.
  - rewrite (HD v Hv). solve_cnt.
  - rewrite (HD v Hv). solve_cnt.
  - rewrite (HD v Hv). unfold sum. erewrite IHP1, IHP2; eauto.
  - rewrite (HD v Hv). solve_cnt.
Qed.

Lemma ws_cnt : forall M N P, ws_proc M N P -> forall v, N <= v -> cnt_proc v P = 0.
Proof.
  intros M N P H; induction P; intros v Hv; inversion H; subst; simpl.
  - destruct o; inversion WSO; subst; simpl; solve_cnt.
  - solve_cnt.
  - solve_cnt.
  - rewrite IHP1, IHP2; auto.
  - auto.
Qed.

Lemma wf_linv : forall m0 n0 m n P,
    wf_term m0 n0 (bag m n P) -> linv (m + m0) (n + n0) n (flatten P).
Proof.
  intros m0 n0 m n P H.
  inversion H; subst.
  assert (HWS : ws_proc (m + m0) (n + n0) P) by (eapply wf_ws_proc; eauto).
  repeat split.
  - lia.
  - apply flatten_atoms.
  - now apply ws_flatten.
  - intros v. rewrite cnt_flatten.
    destruct (lt_dec v (n + n0)).
    + rewrite (wf_cnt _ _ _ _ _ WFP v l).
      unfold ctxt_app, flat_ctxt. destruct (lt_dec v n); try lia.
      destruct (UD v l0); lia.
    + rewrite (ws_cnt _ _ _ HWS v); lia.
  - intros v Hv. rewrite cnt_flatten.
    destruct (lt_dec v (n + n0)).
    + rewrite (wf_cnt _ _ _ _ _ WFP v l).
      unfold ctxt_app, flat_ctxt. destruct (lt_dec v n); lia.
    + rewrite (ws_cnt _ _ _ HWS v); lia.
Qed.

(* -- The multiset equivalence is structural + nu-equivalence -------------- *)

(* The equivalence on terms generated by ≈t and nu-equivalence. *)
Definition term_eqv : term -> term -> Prop :=
  clos_refl_sym_trans term (fun t t' => t ≈t t' \/ t [t≡ ] t').

Lemma unflatten_rnm : forall s l, rnm s (unflatten l) = unflatten (map (rnm s) l).
Proof. induction l; simpl; auto. unfold rnm in *; simpl; now rewrite IHl. Qed.

Lemma ws_unflatten : forall M N l, Forall (ws_proc M N) l -> ws_proc M N (unflatten l).
Proof. induction l; simpl; intros H; constructor; inversion H; auto. Qed.

Lemma aeq_rnm : forall M N s P, ws_proc M N P ->
    aeq_proc M N (ren_id M) s P (rnm s P).
Proof.
  intros M N s P H. unfold rnm.
  induction P; inversion H; subst; simpl; try constructor; auto.
  destruct o; inversion WSO; subst; simpl; constructor; auto.
  now apply aeq_id_refl_tpo.
Qed.

Lemma swap_wf_ren : forall n a b, a < n -> b < n -> @wf_ren n n (swap a b).
Proof.
  intros n a b Ha Hb x; split; intros.
  - now apply swap_lt.
  - rewrite (swap_ge a b n x); auto.
Qed.

Lemma swap_wf_bij : forall n a b, a < n -> b < n -> @wf_bij_ren n (swap a b).
Proof.
  intros n a b Ha Hb.
  exists (swap_wf_ren n a b Ha Hb).
  exists (swap a b). split; [ now apply swap_wf_ren | ].
  intros x; split; intros; rewrite !swap_invol; split; auto.
Qed.

Lemma bij_app_swap : forall n n0 a b, a < n -> b < n ->
    @bij_app n n0 (swap a b) (ren_id n0) = swap a b.
Proof.
  intros. apply functional_extensionality; intros x.
  unfold bij_app, ctxt_app, ren_id.
  destruct (lt_dec x n); auto.
  rewrite (swap_ge a b n x); lia.
Qed.

Lemma eqv1_term_eqv : forall m0 n0 m n l l',
    linv (m + m0) (n + n0) n l -> eqv1 n l l' ->
    term_eqv (bag m n (unflatten l)) (bag m n (unflatten l')).
Proof.
  intros m0 n0 m n l l' HI H. apply rst_step.
  inversion H; subst.
  - left. constructor. now apply perm_unflatten.
  - left. constructor. simpl. apply seq_par_cong; [ | reflexivity ].
    inversion H0; subst; auto.
  - right. apply neq_term_intro with (m := m0) (n := n0).
    apply aeq_bag with (bf' := ren_id m) (br' := swap a b).
    + apply wf_bij_ren_id.
    + now apply swap_wf_bij.
    + rewrite bij_app_id, bij_app_swap; auto.
      rewrite <- unflatten_rnm. apply aeq_rnm.
      destruct HI as (_ & _ & HW & _). now apply ws_unflatten.
Qed.

Lemma leqv_term_eqv : forall m0 n0 m n l l',
    linv (m + m0) (n + n0) n l -> leqv n l l' ->
    term_eqv (bag m n (unflatten l)) (bag m n (unflatten l')).
Proof.
  intros m0 n0 m n l l' HI H. revert HI.
  induction H; intros.
  - eapply eqv1_term_eqv; eauto.
  - apply rst_refl.
  - apply rst_sym. apply IHclos_refl_sym_trans.
    eapply linv_leqv; eauto. now apply leqv_sym.
  - apply rst_trans with (bag m n (unflatten y)).
    + now apply IHclos_refl_sym_trans1.
    + apply IHclos_refl_sym_trans2. eapply linv_leqv; eauto.
Qed.

(* -- Simulating term steps by multiset steps, and back --------------------- *)

(* [t] is the bag [m n] whose body flattens to [l], up to the equivalence. *)
Definition corr (m n : nat) (l : list proc) (t : term) : Prop :=
  exists P, t = bag m n P /\ leqv n (flatten P) l.

Lemma top_lin_step_lift : forall m n l t t1,
    corr m n l t -> top_lin_step t t1 ->
    exists l1, lstep l l1 /\ corr m n l1 t1.
Proof.
  intros m n l t t1 (P & -> & HE) (t0 & Hseq & HS).
  inversion Hseq as [m' n' P' P2 HP]; subst.
  destruct (top_lin_prim_lstep _ _ HS) as (m'' & n'' & P0 & P1 & E0 & -> & HL).
  injection E0 as <- <- <-.
  assert (HE2 : leqv n (flatten P2) l).
  { eapply leqv_trans; [ | apply HE ].
    apply leqv_sym, peqv_leqv, seq_flatten; auto. }
  destruct (leqv_sim _ _ _ _ HE2 HL) as (l1 & HL1 & HE1).
  exists l1; split; auto. exists P1; split; auto.
Qed.

Lemma lstep_lower : forall m n l l1 t,
    corr m n l t -> lstep l l1 ->
    exists t1, top_lin_step t t1 /\ corr m n l1 t1.
Proof.
  intros m n l l1 t (P & -> & HE) HL.
  destruct (leqv_sim _ _ _ _ (leqv_sym _ _ _ HE) HL) as (l1' & HL' & HE').
  destruct (lstep_top_lin m n P l1' HL') as (P1 & HS & HF).
  exists (bag m n P1); split; auto. exists P1; split; auto.
  rewrite HF. now apply leqv_sym.
Qed.

Lemma top_lin_steps_lift : forall m n t t1, top_lin_steps t t1 ->
    forall l, corr m n l t -> exists l1, steps lstep l l1 /\ corr m n l1 t1.
Proof.
  intros m n t t1 H; induction H; intros.
  - exists l; split; auto. constructor.
  - destruct (top_lin_step_lift _ _ _ _ _ H1 H) as (l1 & HL & HC).
    destruct (IHclos_refl_trans_1n _ HC) as (l2 & HL2 & HC2).
    exists l2; split; auto. econstructor; eauto.
Qed.

Lemma lsteps_lower : forall m n l l1, steps lstep l l1 ->
    forall t, corr m n l t -> exists t1, top_lin_steps t t1 /\ corr m n l1 t1.
Proof.
  intros m n l l1 H; induction H; intros.
  - exists t; split; auto. constructor.
  - destruct (lstep_lower _ _ _ _ _ H1 H) as (t1 & HS & HC).
    destruct (IHclos_refl_trans_1n _ HC) as (t2 & HS2 & HC2).
    exists t2; split; auto. econstructor; eauto.
Qed.

Lemma linv_lsteps : forall M N n l l1, steps lstep l l1 -> linv M N n l -> linv M N n l1.
Proof.
  intros M N n l l1 H; induction H; intros; auto.
  apply IHclos_refl_trans_1n. eapply linv_lstep; eauto.
Qed.


(* ========================================================================== *)
(* MAIN THEOREM                                                               *)
(* ========================================================================== *)

(* The top-level linear fragment of LinOpal is confluent, modulo the
   equivalence generated by structural equivalence and nu-equivalence.

   [top_lin_steps] is a sub-relation of [multi_step]
   (see [top_lin_steps_multi_step]). *)
Theorem top_linear_confluence : forall m0 n0 t t1 t2,
    wf_term m0 n0 t ->
    top_lin_steps t t1 ->
    top_lin_steps t t2 ->
    exists t3 t4,
      top_lin_steps t1 t3 /\ top_lin_steps t2 t4 /\ term_eqv t3 t4.
Proof.
  intros m0 n0 [m n P] t1 t2 HWF H1 H2.
  pose proof (wf_linv _ _ _ _ _ HWF) as HI.
  assert (HC : corr m n (flatten P) (bag m n P))
    by (exists P; split; auto; apply leqv_refl).
  destruct (top_lin_steps_lift _ _ _ _ H1 _ HC) as (l1 & HL1 & HC1).
  destruct (top_lin_steps_lift _ _ _ _ H2 _ HC) as (l2 & HL2 & HC2).
  destruct (lstep_confluence _ _ _ _ _ _ HI HL1 HL2) as (l3 & l4 & HL3 & HL4 & HE).
  destruct (lsteps_lower _ _ _ _ HL3 _ HC1) as (t3 & HS3 & (P3 & -> & HE3)).
  destruct (lsteps_lower _ _ _ _ HL4 _ HC2) as (t4 & HS4 & (P4 & -> & HE4)).
  exists (bag m n P3), (bag m n P4); repeat split; auto.
  (* The two results are equivalent *)
  assert (HI3 : linv (m + m0) (n + n0) n (flatten P3)).
  { eapply linv_leqv; [ apply leqv_sym, HE3 | ].
    eapply linv_lsteps; [ apply HL3 | ].
    eapply linv_lsteps; [ apply HL1 | apply HI ]. }
  assert (HE34 : leqv n (flatten P3) (flatten P4)).
  { eapply leqv_trans; [ apply HE3 | ].
    eapply leqv_trans; [ apply HE | apply leqv_sym, HE4 ]. }
  apply rst_trans with (bag m n (unflatten (flatten P3))).
  { apply rst_step; left. constructor. apply seq_proc_symm, unflatten_flatten. }
  apply rst_trans with (bag m n (unflatten (flatten P4))).
  { eapply leqv_term_eqv; eauto. }
  apply rst_step; left. constructor. apply unflatten_flatten.
Qed.


(* ========================================================================== *)
(* PART 4.  Confluence up to bisimulation, for the full [step] relation       *)
(* ========================================================================== *)

(* LinOpal is not syntactically confluent, even up to ≈t and alpha: once
   steps under lambdas are allowed, a body can be unfolded in different
   orders and the results only agree "up to unfolding" (cf. the
   [breaks_confluence] example in Confluence.v).  The right target is
   confluence up to a bisimulation: both reducts can be continued to terms
   that are bisimilar.  This part sets up that notion abstractly and proves
   the general theorem that reduces it to a local diagram, plus the facts
   about the full [step] relation that we can already establish. *)

Section BisimConfluence.

  Variable A : Type.
  Variable step : A -> A -> Prop.

  (* [Obs] is the observation that bisimilar terms must agree on.  It must
     be an equivalence.  (With a trivial [Obs], every two normal forms would
     be bisimilar, so the choice of [Obs] is what gives the theorem
     content; for LinOpal it should be the observation of the free
     variables, cf. Observations.v.) *)
  Variable Obs : A -> A -> Prop.
  Hypothesis Obs_refl : forall x, Obs x x.
  Hypothesis Obs_sym : forall x y, Obs x y -> Obs y x.
  Hypothesis Obs_trans : forall x y z, Obs x y -> Obs y z -> Obs x z.

  (* A (strong) bisimulation that respects the observation. *)
  Definition is_bisim (R : A -> A -> Prop) : Prop :=
    forall x y, R x y ->
      Obs x y /\
      (forall x', step x x' -> exists y', step y y' /\ R x' y') /\
      (forall y', step y y' -> exists x', step x x' /\ R x' y').

  Definition bisimilar (x y : A) : Prop :=
    exists R, is_bisim R /\ R x y.

  Lemma bisimilar_is_bisim : is_bisim bisimilar.
  Proof.
    intros x y (R & HR & Hxy).
    destruct (HR _ _ Hxy) as (HO & H1 & H2).
    repeat split; auto.
    - intros x' Hx. destruct (H1 _ Hx) as (y' & ? & ?).
      exists y'; split; auto. exists R; auto.
    - intros y' Hy. destruct (H2 _ Hy) as (x' & ? & ?).
      exists x'; split; auto. exists R; auto.
  Qed.

  Lemma bisimilar_refl : forall x, bisimilar x x.
  Proof.
    intros x. exists eq; split; auto.
    intros a b ->; repeat split; auto; intros; eauto.
  Qed.

  Lemma bisimilar_sym : forall x y, bisimilar x y -> bisimilar y x.
  Proof.
    intros x y (R & HR & Hxy).
    exists (fun a b => R b a); split; auto.
    intros a b Hab. destruct (HR _ _ Hab) as (HO & H1 & H2).
    repeat split; auto.
  Qed.

  Lemma bisimilar_trans : forall x y z,
      bisimilar x y -> bisimilar y z -> bisimilar x z.
  Proof.
    intros x y z (R1 & HR1 & H1) (R2 & HR2 & H2).
    exists (fun a c => exists b, R1 a b /\ R2 b c); split; eauto.
    intros a c (b & Hab & Hbc).
    destruct (HR1 _ _ Hab) as (HO1 & F1 & B1).
    destruct (HR2 _ _ Hbc) as (HO2 & F2 & B2).
    repeat split; eauto.
    - intros a' Ha. destruct (F1 _ Ha) as (b' & Hb & Hab').
      destruct (F2 _ Hb) as (c' & Hc & Hbc'). eauto.
    - intros c' Hc. destruct (B2 _ Hc) as (b' & Hb & Hbc').
      destruct (B1 _ Hb) as (a' & Ha & Hab'). eauto.
  Qed.

  Lemma bisimilar_sim : forall x x' y, bisimilar x x' -> step x y ->
      exists y', step x' y' /\ bisimilar y y'.
  Proof.
    intros. destruct (bisimilar_is_bisim _ _ H) as (_ & F & _). auto.
  Qed.

  (* Confluence up to bisimulation. *)
  Definition confluent_up_to_bisim (Inv : A -> Prop) : Prop :=
    forall x y1 y2, Inv x ->
      steps step x y1 -> steps step x y2 ->
      exists z1 z2, steps step y1 z1 /\ steps step y2 z2 /\ bisimilar z1 z2.

  Variable Inv : A -> Prop.
  Hypothesis Inv_step : forall x y, Inv x -> step x y -> Inv y.
  Hypothesis Inv_bisim : forall x y, Inv x -> bisimilar x y -> Inv y.

  (* Route 1: a local diamond up to bisimilarity (each side may take 0 or 1
     steps) suffices. *)
  Theorem confluence_up_to_bisim_local :
    (forall x y1 y2, Inv x -> step x y1 -> step x y2 ->
       exists z1 z2, clos_refl _ step y1 z1 /\ clos_refl _ step y2 z2 /\
                     bisimilar z1 z2) ->
    confluent_up_to_bisim Inv.
  Proof.
    intros HD x y1 y2 HI H1 H2.
    exact (confluence_modulo A step bisimilar Inv bisimilar_refl bisimilar_sym
             bisimilar_trans Inv_step Inv_bisim bisimilar_sim HD x y1 y2 HI H1 H2).
  Qed.

  (* Route 2 (Tait / Martin-Löf): when a step can duplicate redexes (as
     applying a lambda whose body still has redexes does), the one-step
     diamond fails; instead, find a "parallel" step [pstep] with
       step ⊆ pstep ⊆ step*,
     that has the diamond up to bisimilarity, and that bisimilarity
     simulates. *)
  Variable pstep : A -> A -> Prop.
  Hypothesis step_pstep : forall x y, step x y -> pstep x y.
  Hypothesis pstep_steps : forall x y, pstep x y -> steps step x y.

  Lemma Inv_steps : forall x y, Inv x -> steps step x y -> Inv y.
  Proof. intros x y HI H; induction H; eauto. Qed.

  Lemma psteps_steps : forall x y, steps pstep x y -> steps step x y.
  Proof.
    intros x y H; induction H; [ constructor | ].
    eapply steps_trans; eauto.
  Qed.

  Lemma steps_psteps : forall x y, steps step x y -> steps pstep x y.
  Proof. intros x y H; induction H; econstructor; eauto. Qed.

  Theorem confluence_up_to_bisim_parallel :
    (forall x x' y, bisimilar x x' -> pstep x y ->
       exists y', pstep x' y' /\ bisimilar y y') ->
    (forall x y1 y2, Inv x -> pstep x y1 -> pstep x y2 ->
       exists z1 z2, clos_refl _ pstep y1 z1 /\ clos_refl _ pstep y2 z2 /\
                     bisimilar z1 z2) ->
    confluent_up_to_bisim Inv.
  Proof.
    intros HS HD x y1 y2 HI H1 H2.
    apply steps_psteps in H1, H2.
    assert (HIp : forall a b, Inv a -> pstep a b -> Inv b)
      by (intros; eapply Inv_steps; eauto).
    destruct (confluence_modulo A pstep bisimilar Inv bisimilar_refl bisimilar_sym
                bisimilar_trans HIp Inv_bisim HS HD x y1 y2 HI H1 H2)
      as (z1 & z2 & Hz1 & Hz2 & HE).
    exists z1, z2; repeat split; auto using psteps_steps.
  Qed.

End BisimConfluence.

Arguments bisimilar {A}.
Arguments is_bisim {A}.
Arguments confluent_up_to_bisim {A}.


(* -- Facts about the full [step] relation --------------------------------- *)

(* Structural equivalence is a strong simulation for [step], with
   identical results, because [step] already works up to ≈t. *)
Lemma seq_step : forall t t' t1, t ≈t t' -> step t t1 -> step t' t1.
Proof.
  intros t t' t1 HE HS. inversion HS; subst.
  econstructor; [ | eauto ].
  eapply Transitive_seq_term; [ apply Symmetric_seq_term; eauto | auto ].
Qed.

(* Hence ≈t is a bisimulation for [step] (for any observation that
   ≈t-equivalent terms agree on), so ≈t ⊆ bisimilar. *)
Lemma seq_bisimilar : forall (Obs : term -> term -> Prop),
    (forall t t', t ≈t t' -> Obs t t') ->
    forall t t', t ≈t t' -> bisimilar step Obs t t'.
Proof.
  intros Obs HO t t' H. exists seq_term; split; auto.
  intros a b Hab; repeat split; auto.
  - intros a' Ha. exists a'; split; [ eapply seq_step; eauto | reflexivity ].
  - intros b' Hb. exists b'; split; [ | reflexivity ].
    eapply seq_step; eauto. now symmetry.
Qed.

(* The fragment proven in PART 3 is part of [step]. *)
Lemma top_lin_steps_steps : forall t t', top_lin_steps t t' -> steps step t t'.
Proof.
  intros t t' H; induction H; econstructor; eauto using top_lin_step_step.
Qed.

(* The target statement for all of LinOpal: confluence of [step] (all
   rules, including steps under lambdas) up to bisimilarity, for a given
   observation [Obs].  It is stated here as a definition, not proven; see
   the closing comment for the plan. *)
Definition LinOpal_confluent_up_to_bisim (Obs : term -> term -> Prop) : Prop :=
  confluent_up_to_bisim step Obs (fun t => exists m n, wf_term m n t).


